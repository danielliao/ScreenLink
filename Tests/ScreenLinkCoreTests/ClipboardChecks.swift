import Foundation
import ScreenLinkCore

func runClipboardChecks() {
    let aID = UUID(uuidString: "00000000-0000-0000-0000-000000000001")!
    let bID = UUID(uuidString: "00000000-0000-0000-0000-000000000002")!
    var a = ClipboardPolicy(deviceID: aID)
    var b = ClipboardPolicy(deviceID: bID)
    check(a.localChange(changeCount: 1, fingerprint: "private", now: 1000) == nil, "Clipboard is inactive by default")
    a.setAccess(enabled: true, unlocked: true, changeCount: 5, now: 1000)
    b.setAccess(enabled: true, unlocked: true, changeCount: 5, now: 1000)
    check(a.localChange(changeCount: 5, fingerprint: "old", now: 1000) == nil, "Enabling baselines old clipboard")
    guard let ea = a.localChange(changeCount: 6, fingerprint: "A", now: 1001) else { check(false, "New unlocked local copy produces an event"); return }
    guard let eb = b.localChange(changeCount: 6, fingerprint: "B", now: 1001) else { check(false, "Peer local copy produces an event"); return }
    check(ea < eb, "Simultaneous copies use deterministic sender ordering")
    check(a.prepare(event: eb.encoded, now: 1001) == eb, "Remote event parses and advances logical clock")
    check(a.accept(event: eb, fingerprint: "B"), "Later concurrent copy replaces earlier copy")
    check(!b.accept(event: ea, fingerprint: "A"), "Earlier concurrent copy cannot replace winner")
    check(!a.accept(event: eb, fingerprint: "B"), "Duplicate event is not applied twice")
    a.markWritten(changeCount: 7)
    check(a.localChange(changeCount: 7, fingerprint: "B", now: 1002) == nil, "Remote pasteboard write never echoes")
    check(a.localChange(changeCount: 8, fingerprint: "B", now: 1003) == nil, "Repeated content is not broadcast")
    a.setAccess(enabled: true, unlocked: false, changeCount: 8, now: 1004)
    check(a.prepare(event: eb.encoded, now: 1004) == nil, "Locked device rejects remote clipboard")
    check(a.localChange(changeCount: 9, fingerprint: "locked", now: 1005) == nil, "Locked device does not broadcast")
    a.setAccess(enabled: true, unlocked: true, changeCount: 10, now: 1006)
    check(a.localChange(changeCount: 10, fingerprint: "locked", now: 1006) == nil, "Unlock baselines copies made while locked")
    let remote = b.localChange(changeCount: 9, fingerprint: "remote", now: 1010)!
    _ = a.prepare(event: remote.encoded, now: 1010)
    let local = a.localChange(changeCount: 11, fingerprint: "unsampled", now: 1009)!
    check(local > remote && !a.accept(event: remote, fingerprint: "remote"), "Unsampled local copy wins after observing remote clock despite wall clock rollback")
    _ = a.localChange(changeCount: 12, fingerprint: nil, now: 1011)
    check(!a.accept(event: remote, fingerprint: "remote"), "Unsupported or secret local changes still prevent overwrites")
    check(a.prepare(event: "garbage", now: 1011) == nil, "Malformed event rejected")
    check(a.prepare(event: "1:18446744073709551615:0:\(bID.uuidString)", now: 1011) == nil, "Unbounded timestamp rejected")
    check(a.prepare(event: "1:200000:0:\(bID.uuidString)", now: 1011) == nil, "Far future event cannot poison ordering")
    check(a.prepare(event: "1:1011:18446744073709551615:\(bID.uuidString)", now: 1011) == nil, "Unbounded logical counter rejected")
    check(a.prepare(event: "1:1011:1:not-a-uuid", now: 1011) == nil, "Malformed sender rejected")
    check(a.prepare(event: local.encoded, now: 1011) == nil, "Own relayed event rejected")
    check(ClipboardPolicy.accepts(data: Data(repeating: 65, count: 1_048_576), kind: "text"), "Text at one MiB accepted")
    check(!ClipboardPolicy.accepts(data: Data(repeating: 65, count: 1_048_577), kind: "text"), "Oversized text rejected without truncation")
    check(!ClipboardPolicy.accepts(data: Data([0xff]), kind: "text"), "Non UTF8 text rejected")
    check(!ClipboardPolicy.accepts(data: Data(), kind: "file"), "Unsupported clipboard type rejected")
    check(!ClipboardPolicy.accepts(data: Data(repeating: 0, count: 10_485_761), kind: "png"), "Oversized image rejected")
    check(ClipboardPolicy.blocks(types: ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"]), "Concealed text is never shared")
    check(ClipboardPolicy.blocks(types: ["org.nspasteboard.TransientType"]), "Transient content is never shared")
    check(ClipboardPolicy.blocks(types: ["org.nspasteboard.AutoGeneratedType"]), "Autogenerated content is never shared")
    check(ClipboardPolicy.blocks(types: ["com.agilebits.onepassword"]), "Password manager marked content is never shared")
    check(ClipboardPolicy.blocks(types: ["public.file-url", "public.utf8-plain-text"]), "Copied file path text is not shared")
    check(!ClipboardPolicy.blocks(types: ["public.utf8-plain-text"]), "Ordinary text is shareable")
}
