import Foundation

public struct ClipboardEvent: Comparable, Equatable {
    public let timestamp: UInt64
    public let counter: UInt64
    public let sender: UUID
    public var encoded: String { "1:\(timestamp):\(counter):\(sender.uuidString)" }
    public static func < (lhs: Self, rhs: Self) -> Bool {
        (lhs.timestamp, lhs.counter, lhs.sender.uuidString) < (rhs.timestamp, rhs.counter, rhs.sender.uuidString)
    }
}

/// Pure ordering and access policy. Contains only metadata and content digests.
public struct ClipboardPolicy {
    private let deviceID: UUID
    private var active = false
    private var changeCount = 0
    private var fingerprint: String?
    private var latest: ClipboardEvent?
    private var clockTimestamp: UInt64 = 0
    private var clockCounter: UInt64 = 0
    private static let maxTimestamp: UInt64 = 253_402_300_799_999
    private static let maxCounter: UInt64 = 1_000_000_000

    public init(deviceID: UUID) { self.deviceID = deviceID }

    public mutating func setAccess(enabled: Bool, unlocked: Bool, changeCount: Int, now: UInt64) {
        let next = enabled && unlocked
        guard next != active else { return }
        active = next
        self.changeCount = changeCount
        fingerprint = nil
        // A new access interval cannot replay an event from a previous interval.
        latest = nextEvent(now: now)
    }

    public mutating func localChange(changeCount: Int, fingerprint: String?, now: UInt64) -> ClipboardEvent? {
        guard active, changeCount != self.changeCount else { return nil }
        self.changeCount = changeCount
        let event = nextEvent(now: now)
        latest = event
        let repeated = fingerprint == self.fingerprint
        self.fingerprint = fingerprint
        return fingerprint != nil && !repeated ? event : nil
    }

    /// Observe the incoming clock before sampling the local pasteboard. A local
    /// user copy not yet sampled will then supersede that incoming event.
    public mutating func prepare(event: String, now: UInt64) -> ClipboardEvent? {
        guard active, event.utf8.count <= 100 else { return nil }
        let parts = event.split(separator: ":", omittingEmptySubsequences: false)
        guard parts.count == 4, parts[0] == "1",
              let timestamp = UInt64(parts[1]), timestamp <= Self.maxTimestamp,
              timestamp <= now || timestamp - now <= 30_000,
              let counter = UInt64(parts[2]), counter <= Self.maxCounter,
              let sender = UUID(uuidString: String(parts[3])), sender != deviceID else { return nil }
        let parsed = ClipboardEvent(timestamp: timestamp, counter: counter, sender: sender)
        guard parsed.encoded == event else { return nil }
        if (timestamp, counter) > (clockTimestamp, clockCounter) {
            clockTimestamp = timestamp
            clockCounter = counter
        }
        return parsed
    }

    public mutating func accept(event: ClipboardEvent, fingerprint: String) -> Bool {
        guard active, latest.map({ event > $0 }) ?? true else { return false }
        latest = event
        let changed = self.fingerprint != fingerprint
        self.fingerprint = fingerprint
        return changed
    }

    public mutating func markWritten(changeCount: Int) { self.changeCount = changeCount }

    private mutating func nextEvent(now: UInt64) -> ClipboardEvent {
        if now > clockTimestamp {
            clockTimestamp = min(now, Self.maxTimestamp)
            clockCounter = 0
        } else if clockCounter < Self.maxCounter {
            clockCounter += 1
        } else {
            clockTimestamp = min(clockTimestamp + 1, Self.maxTimestamp)
            clockCounter = 0
        }
        return ClipboardEvent(timestamp: clockTimestamp, counter: clockCounter, sender: deviceID)
    }

    public static func accepts(data: Data, kind: String) -> Bool {
        switch kind {
        case "text": return data.count <= 1_048_576 && String(data: data, encoding: .utf8) != nil
        case "png":
            return data.count <= 10_485_760 && data.starts(with: [137, 80, 78, 71, 13, 10, 26, 10])
        default: return false
        }
    }

    public static func blocks(types: [String]) -> Bool {
        types.contains { raw in
            let type = raw.lowercased()
            return type == "public.file-url" || type == "nsfilenamespboardtype" ||
                type.contains("concealed") || type.contains("transient") ||
                type.contains("autogenerated") || type.contains("agilebits") ||
                type.contains("1password") || type.contains("onepassword") ||
                type.contains("keepass") || type.contains("bitwarden")
        }
    }
}
